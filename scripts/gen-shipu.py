def parse_md_links(path):
    links = {}
    with open(path, encoding='utf-8') as f:
        for line in f:
            m = re.match(r'\s*-\s*\*\*(.+?)\*\*\s*(?:—\s*(.*))?$', line.strip())
            if not m:
                continue
            title = m.group(1).strip()
            rest = (m.group(2) or '').strip()
            url = None
            um = re.search(r'(https?://\S+)', rest)
            if um:
                url = um.group(1).rstrip(').,')
            links[title] = {'url': url, 'rest': rest}
    return links


def source_name(url, rest):
    if not url:
        return rest.split(' ')[0] if rest else '家常'
    host = re.sub(r'^https?://(www\.|m\.)?', '', url).split('/')[0]
    mapping = {
        'instagram.com': 'Instagram',
        'cookpad.com': 'Cookpad',
        'hk.lkk.com': '李錦記',
        'lkk.com': '李錦記',
        'betiskitchen.com': "Beti's Kitchen",
        'istidiningtable.com': 'Isti Dining Table',
        'christinesrecipes.com': "Christine's Recipes",
        'butcher.hk': 'butcher.hk',
        'xiachufang.com': '下廚房',
        'bigboyrecipe.com': 'Big Boy Recipe',
        'afterwork-kitchen.com': 'Afterwork Kitchen',
        'elanie-kitchen.blogspot.com': 'Elanie Kitchen',
    }
    for k, v in mapping.items():
        if host.endswith(k):
            return v
    if host.endswith('pixnet.net'):
        return 'PIXNET'
    return host


